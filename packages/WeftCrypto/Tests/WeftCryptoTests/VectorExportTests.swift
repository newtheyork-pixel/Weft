import XCTest
import CryptoKit
@testable import WeftCrypto

/// Exports cross-language interop vectors the JS dev's test can consume.
/// Writes to the package's TestVectors/ dir when WEFT_EXPORT_VECTORS=1 (so a normal
/// `swift test` run is non-mutating, but `WEFT_EXPORT_VECTORS=1 swift test` regenerates them).
///
/// Each vector is produced by THIS code so JS can verify it interoperates:
///  - wrapped_privkey: a real PBKDF2/AES-GCM blob + the passphrase + the recovered scalars/kids.
///  - signed_identity: a bootstrapped identity's signed roster rows (signing self-signed; identity
///    signed by signing) + the canonical payloads (hex) so JS can re-derive and verify.
final class VectorExportTests: XCTestCase {

    struct Vectors: Codable {
        struct WrappedPrivKey: Codable {
            let passphrase: String
            let blob: String
            let kdf_params: KdfParams
            let expect_identity_d_b64url: String
            let expect_signing_d_b64url: String
            let expect_identity_kid: String
            let expect_signing_kid: String
            let userkey_aad_utf8: String
        }
        struct SignedIdentity: Codable {
            let owner_user_id: String
            let sig_domain: String
            let signing: SignedRosterEntry
            let identity: SignedRosterEntry
            let signing_canonical_payload_hex: String
            let identity_canonical_payload_hex: String
        }
        let note: String
        let suite: String
        let wrapped_privkey: WrappedPrivKey
        let signed_identity: SignedIdentity
    }

    func testExportInteropVectors() throws {
        // Deterministic inputs so the exported vector is stable when regenerated.
        let passphrase = "weft-interop-passphrase"
        let salt = Data((0..<16).map { UInt8($0) })          // 00..0f
        let nonce = Data((0..<12).map { UInt8(0x10 + $0) })  // 10..1b

        let id = UserIdentity.generate()
        let (blob, params) = try WeftWrappedPrivateKey.wrap(passphrase: passphrase, identity: id,
                                                            salt: salt, nonce: nonce)
        // Self-check: it opens.
        let reopened = try WeftWrappedPrivateKey.open(passphrase: passphrase, blob: blob)
        XCTAssertEqual(reopened.identityKid, id.identityKid)

        let owner = "11111111-1111-1111-1111-111111111111"
        let (signing, identity) = try id.signedRoster(ownerUserId: owner)

        // Self-check signatures verify.
        let signingRoster = RosterKey(sigDomain: signing.sig_domain, ownerUserId: owner,
                                      keyKind: .signing, pubkeyB64: signing.pubkey, kid: signing.kid,
                                      keyEpoch: signing.key_epoch, predecessorKid: nil)
        XCTAssertTrue(WeftRoster.verify(signingRoster, signatureB64: signing.signature, with: id.signingPublic))
        let identityRoster = RosterKey(sigDomain: identity.sig_domain, ownerUserId: owner,
                                       keyKind: .identity, pubkeyB64: identity.pubkey, kid: identity.kid,
                                       keyEpoch: identity.key_epoch, predecessorKid: nil)
        XCTAssertTrue(WeftRoster.verify(identityRoster, signatureB64: identity.signature, with: id.signingPublic))

        let vectors = Vectors(
            note: "Generated by WeftCrypto (Swift) VectorExportTests. JS interop must: (1) open wrapped_privkey with passphrase and recover the same scalars/kids; (2) verify both ECDSA signatures over SHA-256(canonical payload) using the signing pubkey.",
            suite: WeftConstants.suite,
            wrapped_privkey: .init(
                passphrase: passphrase, blob: blob, kdf_params: params,
                expect_identity_d_b64url: B64.urlEncodeNoPad(id.identityPrivate.rawRepresentation),
                expect_signing_d_b64url: B64.urlEncodeNoPad(id.signingPrivate.rawRepresentation),
                expect_identity_kid: id.identityKid,
                expect_signing_kid: id.signingKid,
                userkey_aad_utf8: "weft-userkey/v1"),
            signed_identity: .init(
                owner_user_id: owner, sig_domain: signing.sig_domain,
                signing: signing, identity: identity,
                signing_canonical_payload_hex: signingRoster.canonicalPayload().map { String(format: "%02x", $0) }.joined(),
                identity_canonical_payload_hex: identityRoster.canonicalPayload().map { String(format: "%02x", $0) }.joined())
        )

        let enc = JSONEncoder()
        enc.outputFormatting = [.prettyPrinted, .sortedKeys]
        let data = try enc.encode(vectors)

        // Always print so the vector is visible in test logs.
        print("=== WEFT INTEROP VECTORS (swift-core) ===")
        print(String(data: data, encoding: .utf8)!)
        print("=== END VECTORS ===")

        if ProcessInfo.processInfo.environment["WEFT_EXPORT_VECTORS"] == "1" {
            // Write next to the source TestVectors dir (resolve from this file's location).
            let here = URL(fileURLWithPath: #filePath)              // .../Tests/WeftCryptoTests/VectorExportTests.swift
            let pkgRoot = here.deletingLastPathComponent()          // WeftCryptoTests
                .deletingLastPathComponent()                        // Tests
                .deletingLastPathComponent()                        // package root
            let outDir = pkgRoot.appendingPathComponent("TestVectors")
            try FileManager.default.createDirectory(at: outDir, withIntermediateDirectories: true)
            let outFile = outDir.appendingPathComponent("weft_swift_vectors.json")
            try data.write(to: outFile)
            print("Wrote vectors to \(outFile.path)")

            // Also emit the two fixtures the JS interop test (interop.test.mjs) consumes directly,
            // so cross-language interop is a repeatable `WEFT_EXPORT_VECTORS=1 swift test && npm test`.
            let wrappedJS: [String: Any] = [
                "passphrase": passphrase,
                "blob": blob,
                "identity_d_b64url": B64.urlEncodeNoPad(id.identityPrivate.rawRepresentation),
                "signing_d_b64url": B64.urlEncodeNoPad(id.signingPrivate.rawRepresentation),
            ]
            try JSONSerialization.data(withJSONObject: wrappedJS, options: [.prettyPrinted, .sortedKeys])
                .write(to: outDir.appendingPathComponent("wrapped_privkey.json"))

            let signedJS: [String: Any] = [
                "owner_user_id": owner,
                "key_kind": "identity",
                "pubkey": identity.pubkey,
                "kid": identity.kid,
                "key_epoch": identity.key_epoch,
                "predecessor_kid": NSNull(),
                "sig_domain": identity.sig_domain,
                "signer_kid": identity.signer_kid,
                "signature": identity.signature,
                "signing_pubkey": id.signingPubkeyB64,
            ]
            try JSONSerialization.data(withJSONObject: signedJS, options: [.prettyPrinted, .sortedKeys])
                .write(to: outDir.appendingPathComponent("signed_identity.json"))
            print("Wrote JS interop fixtures: wrapped_privkey.json, signed_identity.json")
        }
    }
}
